    /**
     * Nearest signature in [entries], or null when nothing lands within the donor's tolerances.
     * See [ArrowSignature.match].
     */
    fun match(signature: BitGrid225): ArrowSignature.Match? = ArrowSignature.match(signature, entries)

    /**
     * Instrument-panel glyph for a matched drawable name (`zn1.b`). Unknown names answer 11
     * (STRAIGHT) exactly as the donor does - on the panel that is the neutral "keep going" arrow.
     *
     * The donor's quirks are kept verbatim: `_l_lhs` and `_r_uk` both answer 17, and the only
     * "straight roundabout with a UK flag" spelling it knows is `directions_roundabout_uk_s`.
     */
    fun iconFor(name: String): Int = when (stripPrefix(name)) {
        "direction_left" -> 1
        "direction_right" -> 2
        "direction_exit_left" -> 3
        "direction_exit_right" -> 5
        "direction_u_turn" -> 9
        "direction_u_turn_lhs" -> 10
        "direction_u_turn_uk" -> 10
        "directions_roundabout_l" -> 15
        "directions_roundabout_r_lhs" -> 16
        "directions_roundabout_l_lhs" -> 17
        "directions_roundabout_r_uk" -> 17
        "directions_roundabout_r" -> 18
        "directions_roundabout_s_lhs" -> 19
        "directions_roundabout_uk_s" -> 19
        "directions_roundabout_s" -> 20
        "directions_roundabout_u_lhs" -> 21
        "directions_roundabout_u_uk" -> 21
        "directions_roundabout_u" -> 22
        "directions_roundabout" -> 25
        "directions_roundabout_lhs" -> 35
        "directions_roundabout_uk" -> 35
        "direction_stop" -> 45
        "direction_end" -> 48
        else -> ICON_STRAIGHT
    }

    /** Lane glyph for a matched drawable name (`zn1.d`); 0 = no lane arrow. */
    fun laneCodeFor(name: String): Int = when (stripPrefix(name)) {
        "direction_left", "direction_exit_left", "keep_left", "fork_left" -> 1
        "direction_straight_left_exit" -> 2
        "direction_right", "direction_exit_right", "keep_right", "fork_right" -> 3
        "direction_straight_right_exit" -> 4
        "direction_u_turn" -> 5
        "direction_t_junction" -> 6
        "direction_u_turn_lhs", "direction_u_turn_uk" -> 8
        else -> 0
    }

    /** Panel glyph for "no usable arrow": the donor sends this rather than nothing. */
    const val ICON_STRAIGHT = 11

    /** True for the roundabout family, whose glyph is replaced by `exit + 24` (or `+ 34`). */
    fun isRoundabout(name: String): Boolean = name.contains("directions_roundabout", ignoreCase = true)

    /** Roundabouts drawn for left-hand traffic occupy the 35..44 block instead of 25..34. */
    fun isLeftHandTraffic(name: String): Boolean =
        name.contains("_lhs", ignoreCase = true) || name.contains("_uk", ignoreCase = true)

    private val PREFIXES = listOf("car_dark_big_", "car_big_trans_", "big_trans_", "big_")

    private fun stripPrefix(name: String): String {
        val lower = name.lowercase()
        for (prefix in PREFIXES) {
            if (lower.startsWith(prefix)) return lower.substring(prefix.length)
        }
        return lower
    }
